#!/usr/bin/env bash
# Install SelfiCamera for the current user: launcher, app menu entry and icon.
# Usage: bash install.sh [--with-model] [--with-shortcuts] [--autostart]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
BIN_DIR="${HOME}/.local/bin"
APP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
ICON_ROOT="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor"

WITH_MODEL=0; WITH_SHORTCUTS=0; AUTOSTART=0
for arg in "$@"; do
    case "$arg" in
        --with-model) WITH_MODEL=1 ;;
        --with-shortcuts) WITH_SHORTCUTS=1 ;;
        --autostart) AUTOSTART=1 ;;
        -h|--help) sed -n '2,3p' "$0"; exit 0 ;;
        *) echo "Unknown option: $arg" >&2; exit 2 ;;
    esac
done

echo "Installing SelfiCamera…"
if ! ldconfig -p 2>/dev/null | grep -q "libxcb-cursor.so.0"; then
    echo "  ! Missing system library libxcb-cursor0. Without it the camera cannot stay on top on GNOME."
    echo "    Install it with:  sudo apt install libxcb-cursor0"
fi
mkdir -p "$BIN_DIR" "$APP_DIR" "$ICON_ROOT/scalable/apps" "$ICON_ROOT/256x256/apps"

echo "  • Preparing Python environment (first time can take a minute)"
bash "$SCRIPT_DIR/run.sh" --version >/dev/null

echo "  • Launcher: $BIN_DIR/selficamera"
cat > "$BIN_DIR/selficamera" <<LAUNCHER
#!/usr/bin/env bash
# Generated by SelfiCamera install.sh
exec bash "$SCRIPT_DIR/run.sh" "\$@"
LAUNCHER
chmod +x "$BIN_DIR/selficamera"

echo "  • Icon and app menu entry"
cp -f "$SCRIPT_DIR/assets/icons/selficamera.svg" "$ICON_ROOT/scalable/apps/selficamera.svg"
cp -f "$SCRIPT_DIR/assets/icons/selficamera.png" "$ICON_ROOT/256x256/apps/selficamera.png"
sed "s|^Exec=selficamera|Exec=$BIN_DIR/selficamera|" "$SCRIPT_DIR/selficamera.desktop" > "$APP_DIR/selficamera.desktop"
command -v update-desktop-database >/dev/null && update-desktop-database "$APP_DIR" 2>/dev/null || true
command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -f -t "$ICON_ROOT" 2>/dev/null || true

if [ "$WITH_MODEL" = 1 ]; then
    echo "  • AI background model"
    "$BIN_DIR/selficamera" --install-model || echo "    (model download failed — retry later with: selficamera --install-model)"
fi
if [ "$WITH_SHORTCUTS" = 1 ]; then
    echo "  • GNOME shortcuts"
    "$BIN_DIR/selficamera" --install-shortcuts || true
fi
if [ "$AUTOSTART" = 1 ]; then
    mkdir -p "${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
    cp -f "$APP_DIR/selficamera.desktop" "${XDG_CONFIG_HOME:-$HOME/.config}/autostart/selficamera.desktop"
    echo "  • Starts at login"
fi

echo
echo "Done. Open “SelfiCamera” from your apps, or run: selficamera"
[ "$WITH_MODEL" = 1 ] || echo "Tip: enable accurate AI background effects with: selficamera --install-model"
[ "$WITH_SHORTCUTS" = 1 ] || echo "Tip: add global shortcuts on GNOME with:       selficamera --install-shortcuts"
case ":$PATH:" in *":$BIN_DIR:"*) ;; *) echo "Note: add $BIN_DIR to your PATH to run 'selficamera' from a terminal." ;; esac
